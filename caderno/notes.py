"""Reading, indexing and checking a caderno notebook.

Standard library only: the CLI runs on any machine with Python 3.9+, and the
service imports this same module so both agree on what a note is.

A note is a markdown file with a small front matter block:

    ---
    description: one line an agent reads to decide whether to open the file
    type: lesson
    ---
    The body. Anything you want.

The file's path (without ``.md``) is the note's key, e.g. ``memory/newsfeed-deploys``.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path

# Folders whose notes are searchable. identity/ is left out on purpose: it is
# loaded at the start of every session, so it never needs to be recalled.
SEARCHABLE_DIRS = ("memory", "machines")
ARCHIVE_DIR = "_archive"
INDEX_NAME = "INDEX.md"
NOTE_TYPES = ("lesson", "preference", "project", "person", "machine", "reference")
SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,79}$")

GENERATED_MARK = "<!-- generated by `caderno index`; edit the notes, not this file -->"


@dataclass
class Note:
    key: str  # e.g. "memory/newsfeed-deploys"
    path: Path
    meta: dict = field(default_factory=dict)
    body: str = ""

    @property
    def description(self) -> str:
        return self.meta.get("description", "").strip()

    @property
    def type(self) -> str:
        return self.meta.get("type", "").strip() or "lesson"

    @property
    def name(self) -> str:
        return self.key.rsplit("/", 1)[-1]

    def content_hash(self) -> str:
        h = hashlib.sha256()
        h.update(self.description.encode())
        h.update(b"\0")
        h.update(self.type.encode())
        h.update(b"\0")
        h.update(self.body.strip().encode())
        return h.hexdigest()

    def embed_text(self) -> str:
        return f"{self.description}\n\n{self.body.strip()}"


def parse(text: str) -> tuple[dict, str]:
    """Split front matter from body. Only flat ``key: value`` lines are read."""
    if not text.startswith("---"):
        return {}, text
    lines = text.splitlines()
    meta: dict = {}
    for i, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            body = "\n".join(lines[i + 1 :])
            return meta, body.lstrip("\n")
        if ":" in line and not line.startswith((" ", "\t")):
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip().strip('"').strip("'")
    # no closing marker: treat the whole thing as body
    return {}, text


def render(meta: dict, body: str) -> str:
    head = "\n".join(f"{k}: {v}" for k, v in meta.items() if v not in (None, ""))
    return f"---\n{head}\n---\n\n{body.strip()}\n"


def load(root: Path, path: Path) -> Note:
    rel = path.relative_to(root).with_suffix("")
    meta, body = parse(path.read_text(encoding="utf-8"))
    return Note(key=rel.as_posix(), path=path, meta=meta, body=body)


def searchable_notes(root: Path) -> list[Note]:
    """Every live note that belongs in search, in a stable order."""
    out = []
    for d in SEARCHABLE_DIRS:
        base = root / d
        if not base.is_dir():
            continue
        for p in sorted(base.rglob("*.md")):
            rel = p.relative_to(base)
            if p.name == INDEX_NAME or rel.parts[0] == ARCHIVE_DIR or p.name.startswith("."):
                continue
            out.append(load(root, p))
    return out


def slugify(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:80].rstrip("-") or "note"


def build_index(root: Path, folder: str = "memory") -> str:
    """The generated one-line-per-note index for a folder.

    Output is deterministic (sorted, no timestamps) so two machines that
    regenerate it from the same files produce identical bytes and git never
    sees a conflict.
    """
    base = root / folder
    notes = [n for n in searchable_notes(root) if n.key.startswith(folder + "/")]
    groups: dict[str, list[Note]] = {}
    for n in notes:
        groups.setdefault(n.type, []).append(n)
    title = folder.capitalize()
    lines = [f"# {title} index", "", GENERATED_MARK, ""]
    if not notes:
        lines.append("_No notes yet._")
    order = [t for t in NOTE_TYPES if t in groups] + sorted(t for t in groups if t not in NOTE_TYPES)
    for t in order:
        lines += [f"## {t}", ""]
        for n in sorted(groups[t], key=lambda n: n.key):
            rel = n.path.relative_to(base).as_posix()
            desc = n.description or "(missing description)"
            lines.append(f"- [{n.name}]({rel}) — {desc}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_indexes(root: Path) -> list[Path]:
    """Regenerate every folder index; return the ones that changed."""
    changed = []
    for folder in SEARCHABLE_DIRS:
        if not (root / folder).is_dir():
            continue
        target = root / folder / INDEX_NAME
        new = build_index(root, folder)
        if not target.exists() or target.read_text(encoding="utf-8") != new:
            target.write_text(new, encoding="utf-8")
            changed.append(target)
    return changed


# --- secrets ---------------------------------------------------------------

# Patterns for credentials that commonly leak into notes. Precision matters
# more than recall here: a false positive blocks a sync, so each pattern needs
# the shape of a real secret, not just a word like "password".
SECRET_PATTERNS = [
    ("private key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
    ("AWS access key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("GitHub token", re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}\b|\bgithub_pat_[A-Za-z0-9_]{40,}\b")),
    ("OpenAI/Anthropic-style key", re.compile(r"\bsk-(?:ant-|proj-)?[A-Za-z0-9_-]{24,}\b")),
    ("Slack token", re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}\b")),
    ("Google API key", re.compile(r"\bAIza[0-9A-Za-z_-]{35}\b")),
    ("bearer token", re.compile(r"(?i)\bbearer\s+[A-Za-z0-9._~+/=-]{24,}")),
    (
        "password assignment",
        re.compile(r"(?i)\b(?:password|passwd|pwd|secret|api[_-]?key|token)\s*[:=]\s*[\"']?(?!<|\$|\{)[^\s\"'`]{6,}"),
    ),
    ("credentials in URL", re.compile(r"\b[a-z][a-z0-9+.-]*://[^\s/:@]+:[^\s/@]{3,}@")),
]


def scan_text(text: str, denylist: list[str] | None = None) -> list[tuple[int, str]]:
    """Return (line number, what matched) for every suspected secret."""
    hits = []
    for i, line in enumerate(text.splitlines(), start=1):
        if "caderno:allow" in line:  # explicit, reviewable escape hatch
            continue
        for label, rx in SECRET_PATTERNS:
            if rx.search(line):
                hits.append((i, label))
                break
        else:
            for word in denylist or []:
                if word and word in line:
                    hits.append((i, "denylisted string"))
                    break
    return hits


def load_denylist(path: Path) -> list[str]:
    if not path.exists():
        return []
    return [
        ln.strip()
        for ln in path.read_text(encoding="utf-8").splitlines()
        if ln.strip() and not ln.lstrip().startswith("#")
    ]


# --- checks ----------------------------------------------------------------


def check(root: Path, denylist: list[str] | None = None) -> list[str]:
    """Problems an agent or a human should fix. Empty list means healthy."""
    problems = []
    if not (root / "INDEX.md").exists():
        problems.append("INDEX.md is missing at the notebook root")
    for n in searchable_notes(root):
        rel = n.path.relative_to(root).as_posix()
        if not n.description:
            problems.append(f"{rel}: no description in front matter")
        if not SLUG_RE.match(n.name):
            problems.append(f"{rel}: file name should be lowercase-with-dashes")
    for folder in SEARCHABLE_DIRS:
        idx = root / folder / INDEX_NAME
        if (root / folder).is_dir() and (not idx.exists() or idx.read_text(encoding="utf-8") != build_index(root, folder)):
            problems.append(f"{folder}/{INDEX_NAME} is out of date (run `caderno index`)")
    for p in sorted(root.rglob("*.md")):
        if ".git" in p.parts:
            continue
        for line, label in scan_text(p.read_text(encoding="utf-8", errors="replace"), denylist):
            problems.append(f"{p.relative_to(root).as_posix()}:{line}: possible secret ({label})")
    return problems
